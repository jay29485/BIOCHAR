def auto_clustering(data, title, features):

    print(f"\n {title}")


    features = [f for f in features if f in data.columns]
    print("Features:", features)

    X = data[features].copy()
    X = X.apply(pd.to_numeric, errors='coerce')
    X = X.fillna(X.median())


    X = X.loc[:, X.nunique() > 1]
    print("Shape:", X.shape)

    if X.shape[1] < 1 or len(X) < 10:
        print(" Not enough data")
        return pd.Series(np.nan, index=data.index)


    X_scaled = StandardScaler().fit_transform(X)


    if X.shape[1] >= 2:
        pca = PCA(n_components=2)
        X_used = pca.fit_transform(X_scaled)
        print(" PCA applied")
    else:
        X_used = X_scaled
        print(" PCA skipped")

    best_score = -1
    best_labels = None
    best_model = ""


    for k in range(2, 7):
        try:
            km = KMeans(n_clusters=k, random_state=42, n_init=10)
            labels = km.fit_predict(X_used)

            if len(set(labels)) > 1:
                score = silhouette_score(X_used, labels)
                print(f"KMeans k={k} → {score:.3f}")

                if score > best_score:
                    best_score = score
                    best_labels = labels
                    best_model = f"KMeans (k={k})"
        except:
            pass


    for k in range(2, 7):
        try:
            agg = AgglomerativeClustering(n_clusters=k)
            labels = agg.fit_predict(X_used)

            if len(set(labels)) > 1:
                score = silhouette_score(X_used, labels)
                print(f"Agglomerative k={k} → {score:.3f}")

                if score > best_score:
                    best_score = score
                    best_labels = labels
                    best_model = f"Agglomerative (k={k})"
        except:
            pass

    for eps in [0.3, 0.5, 0.7]:
        try:
            db = DBSCAN(eps=eps, min_samples=10)
            labels = db.fit_predict(X_used)

            if len(set(labels)) > 1 and -1 not in set(labels):
                score = silhouette_score(X_used, labels)
                print(f"DBSCAN eps={eps} → {score:.3f}")

                if score > best_score:
                    best_score = score
                    best_labels = labels
                    best_model = f"DBSCAN (eps={eps})"
        except:
            pass


    print(f"\n Best Model: {best_model}")
    print(f" Best Silhouette Score: {round(best_score,3)}")

    if X_used.shape[1] >= 2:
        plt.figure(figsize=(6,5))
        sns.scatterplot(x=X_used[:,0], y=X_used[:,1],
                        hue=best_labels, palette="viridis")
        plt.title(f"{title} ({best_model})")
        plt.xlabel("Component 1")
        plt.ylabel("Component 2")
        plt.show()

    return pd.Series(best_labels, index=X.index)


